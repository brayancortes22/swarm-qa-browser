import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { build } from 'esbuild';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = resolve(ROOT, 'packages', 'overlay', 'src', 'index.js');
const TARGETS = [
  resolve(ROOT, 'packages', 'extension', 'overlay.bundle.js'),
  resolve(ROOT, 'packages', 'cdp-adapter', 'overlay.bundle.js'),
  resolve(ROOT, 'packages', 'demo', 'public', 'overlay.bundle.js')
];
const REQUIRED_EXPORTS = ['mountSwarmOverlay', 'runDomAudit', 'MAIN_WORLD_PROBE_SOURCE', 'sanitizeText', 'buildSelector'];

/**
 * Bundles the overlay into a single classic-script IIFE (content scripts and CDP `Runtime.evaluate`
 * cannot load ES modules), smoke-tests it in a VM and writes it next to each adapter.
 */
export async function buildOverlayBundle({ entry = ENTRY, targets = TARGETS } = {}) {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: 'iife',
    target: 'chrome110',
    charset: 'utf8',
    legalComments: 'none',
    write: false,
    banner: { js: '// Generated by scripts/build-overlay.mjs — do not edit. Source: packages/overlay/src' }
  });
  const bundle = result.outputFiles[0].text;

  const sandbox = {};
  new vm.Script(bundle, { filename: 'overlay.bundle.js' }).runInNewContext(sandbox);
  for (const key of REQUIRED_EXPORTS) {
    if (typeof sandbox.__swarmQaOverlayFactory?.[key] !== 'function') throw new Error(`Bundle verification failed: missing factory.${key}`);
  }

  for (const outPath of targets) {
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, bundle, 'utf8');
  }
  return { bundle, bytes: Buffer.byteLength(bundle, 'utf8'), targets };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const res = await buildOverlayBundle();
  process.stdout.write(`Built overlay.bundle.js (${res.bytes} bytes) -> ${res.targets.length} targets\n`);
}
