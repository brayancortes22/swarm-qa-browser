import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OVERLAY_DIR = resolve(ROOT, 'packages', 'overlay', 'src');
const MODULES = [
  'cursor-layer.js',
  'issue-pins.js',
  'network-console.js',
  'dom-auditor.js',
  'overlay-entry.js'
];
const TARGETS = [
  resolve(ROOT, 'packages', 'extension', 'overlay.bundle.js'),
  resolve(ROOT, 'packages', 'cdp-adapter', 'overlay.bundle.js')
];

function transformModule(filename, source) {
  const exported = [];
  let code = source.replace(
    /^[ \t]*import\s+\*\s+as\s+([A-Za-z_$][\w$]*)\s+from\s+['"](\.[^'"]+)['"]\s*;?[ \t]*\r?\n?/gm,
    (_, ns, rel) => `const ${ns} = __modules[${JSON.stringify(rel)}];\n`
  );
  code = code.replace(
    /^[ \t]*import\s*\{([\s\S]*?)\}\s*from\s+['"](\.[^'"]+)['"]\s*;?[ \t]*\r?\n?/gm,
    (_, specifiers, rel) => {
      const mapped = specifiers
        .split(',')
        .map((s) => s.trim())
        .filter(Boolean)
        .map((s) => s.replace(/^([A-Za-z_$][\w$]*)\s+as\s+([A-Za-z_$][\w$]*)$/, '$1: $2'))
        .join(', ');
      return `const { ${mapped} } = __modules[${JSON.stringify(rel)}];\n`;
    }
  );
  code = code.replace(
    /^[ \t]*import\s+['"](\.[^'"]+)['"]\s*;?[ \t]*\r?\n?/gm,
    (_, rel) => `/* side-effect ${rel} */\n`
  );
  if (/^[ \t]*import\b/m.test(code)) {
    throw new Error(`Unsupported non-relative import in ${filename}`);
  }
  code = code.replace(
    /^[ \t]*export\s+((?:async\s+)?function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm,
    (_, decl, name) => {
      exported.push(name);
      return `${decl} ${name}`;
    }
  );
  code = code.replace(/^[ \t]*export\s*\{([\s\S]*?)\}\s*;?[ \t]*\r?\n?/gm, (_, list) => {
    for (const item of list.split(',').map((s) => s.trim()).filter(Boolean)) {
      const m = item.match(/^([A-Za-z_$][\w$]*)(?:\s+as\s+([A-Za-z_$][\w$]*))?$/);
      if (m) exported.push(m[2] ? `${m[2]}: ${m[1]}` : m[1]);
    }
    return '';
  });
  if (/^[ \t]*export\b/m.test(code)) {
    throw new Error(`Unsupported export syntax in ${filename}`);
  }
  return [
    `  __modules[${JSON.stringify(`./${filename}`)}] = (() => {`,
    code.trimEnd(),
    `    return { ${exported.join(', ')} };`,
    '  })();'
  ].join('\n');
}

export function buildOverlayBundle({ overlayDir = OVERLAY_DIR, targets = TARGETS } = {}) {
  const chunks = MODULES.map((file) => {
    const raw = readFileSync(resolve(overlayDir, file), 'utf8');
    return transformModule(file, raw);
  });

  const bundle = [
    '// Auto-generated by scripts/build-overlay.mjs. Do not edit directly.',
    '(() => {',
    "  'use strict';",
    '  const __modules = {};',
    chunks.join('\n\n'),
    "  const { mountSwarmOverlay } = __modules['./overlay-entry.js'];",
    "  const { runDomAudit, sanitizeText, buildSelector } = __modules['./dom-auditor.js'];",
    "  const { MAIN_WORLD_PROBE_SOURCE } = __modules['./network-console.js'];",
    '  globalThis.__swarmQaOverlayFactory = {',
    '    mountSwarmOverlay,',
    '    runDomAudit,',
    '    MAIN_WORLD_PROBE_SOURCE,',
    '    sanitizeText,',
    '    buildSelector',
    '  };',
    '})();',
    ''
  ].join('\n');

  const script = new vm.Script(bundle, { filename: 'overlay.bundle.js' });
  const sandbox = {};
  script.runInNewContext(sandbox);
  const factory = sandbox.__swarmQaOverlayFactory;
  for (const key of ['mountSwarmOverlay', 'runDomAudit', 'MAIN_WORLD_PROBE_SOURCE', 'sanitizeText', 'buildSelector']) {
    if (typeof factory?.[key] !== 'function') {
      throw new Error(`Bundle verification failed: missing factory.${key}`);
    }
  }

  for (const outPath of targets) {
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, bundle, 'utf8');
  }
  return { bundle, bytes: Buffer.byteLength(bundle, 'utf8'), targets };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const res = buildOverlayBundle();
  process.stdout.write(`Built overlay.bundle.js (${res.bytes} bytes) -> ${res.targets.length} targets\n`);
}
